const std = @import("std");
const ArrayList = std.array_list.Managed;
const hir = @import("../hir.zig");
const TokenType = @import("../token.zig").TokenType;

pub const StringWriter = struct {
    list: *ArrayList(u8),

    pub fn writeAll(self: *StringWriter, bytes: []const u8) !void {
        try self.list.appendSlice(bytes);
    }

    pub fn writeByte(self: *StringWriter, byte: u8) !void {
        try self.list.append(byte);
    }

    pub fn print(self: *StringWriter, comptime fmt: []const u8, args: anytype) !void {
        const str = try std.fmt.allocPrint(self.list.allocator, fmt, args);
        defer self.list.allocator.free(str);
        try self.list.appendSlice(str);
    }
};

fn isSvKeyword(name: []const u8) bool {
    const sv_keywords = std.StaticStringMap(void).initComptime(.{
        .{"byte"},
        .{"shortint"},
        .{"int"},
        .{"longint"},
        .{"integer"},
        .{"time"},
        .{"bit"},
        .{"logic"},
        .{"reg"},
        .{"input"},
        .{"output"},
        .{"inout"},
        .{"wire"},
        .{"type"},
        .{"process"},
    });
    return sv_keywords.has(name);
}

fn emitIdent(name: []const u8, writer: anytype) !void {
    if (isSvKeyword(name)) {
        try writer.print("\\{s} ", .{name});
    } else {
        try writer.writeAll(name);
    }
}

pub const SystemVerilogEmitter = struct {
    allocator: std.mem.Allocator,

    pub fn init(allocator: std.mem.Allocator) SystemVerilogEmitter {
        return .{ .allocator = allocator };
    }

    pub fn emitDesign(self: *SystemVerilogEmitter, design: *const hir.HirDesign, writer: anytype) !void {
        try self.emitDesignEx(design, true, writer);
    }

    pub fn emitDesignEx(self: *SystemVerilogEmitter, design: *const hir.HirDesign, emit_tb: bool, writer: anytype) !void {
        try writer.writeAll(
            \\// ==============================================================================
            \\// Generated by ZHdl Compiler (SystemVerilog IEEE 1800-2017 Target)
            \\// DO NOT EDIT DIRECTLY - AUTO-GENERATED FROM ZHDL SOURCE
            \\// ==============================================================================
            \\`timescale 1ns / 1ps
            \\`default_nettype none
            \\/* verilator lint_off DECLFILENAME */
            \\/* verilator lint_off LATCH */
            \\/* verilator lint_off UNUSEDSIGNAL */
            \\/* verilator lint_off CASEINCOMPLETE */
            \\
            \\
        );

        for (design.modules) |mod| {
            try self.emitModule(&mod, writer);
            try writer.writeAll("\n");
        }

        if (emit_tb) {
            for (design.testbenches) |tb| {
                try self.emitTestbench(&tb, writer);
                try writer.writeAll("\n");
            }
        }

        try writer.writeAll("`default_nettype wire\n");
    }

    pub fn emitModule(self: *SystemVerilogEmitter, mod: *const hir.HirModule, writer: anytype) !void {
        try writer.print("module {s} (\n", .{mod.name});

        // Emit ports
        for (mod.ports, 0..) |port, i| {
            const is_last = (i == mod.ports.len - 1);
            const dir_str = switch (port.dir) {
                .in => "input ",
                .out => "output",
                .inout => "inout ",
            };

            const comma = if (is_last) "" else ",";

            if (port.hir_type.tag == .array) {
                try writer.print("    {s} logic [{d}:0] {s} [0:{d}]{s}\n", .{
                    dir_str,
                    port.hir_type.elem_width - 1,
                    port.name,
                    port.hir_type.array_len - 1,
                    comma,
                });
            } else if (port.hir_type.width <= 1) {
                try writer.print("    {s} logic       {s}{s}\n", .{ dir_str, port.name, comma });
            } else {
                try writer.print("    {s} logic [{d:2}:0] {s}{s}\n", .{
                    dir_str,
                    port.hir_type.width - 1,
                    port.name,
                    comma,
                });
            }
        }
        try writer.writeAll(");\n\n");

        // Emit internal signals & registers
        var emitted_signals = std.StringHashMap(void).init(self.allocator);
        defer emitted_signals.deinit();

        for (mod.registers) |reg| {
            if (reg.hir_type.tag == .array) {
                try writer.print("    logic [{d}:0] {s} [0:{d}], {s} [0:{d}];\n", .{
                    reg.hir_type.elem_width - 1,
                    reg.q_name,
                    reg.hir_type.array_len - 1,
                    reg.d_name,
                    reg.hir_type.array_len - 1,
                });
            } else {
                const w = if (reg.hir_type.width > 0) reg.hir_type.width else 1;
                if (w <= 1) {
                    try writer.print("    logic {s}, {s};\n", .{ reg.q_name, reg.d_name });
                } else {
                    try writer.print("    logic [{d}:0] {s}, {s};\n", .{ w - 1, reg.q_name, reg.d_name });
                }
            }
            try emitted_signals.put(reg.q_name, {});
            try emitted_signals.put(reg.d_name, {});
        }

        for (mod.local_signals) |sig| {
            if (emitted_signals.contains(sig.name)) continue;
            // Also avoid declaring if it's already an input/output port
            var is_port = false;
            for (mod.ports) |p| {
                if (std.mem.eql(u8, p.name, sig.name)) {
                    is_port = true;
                    break;
                }
            }
            if (is_port) continue;

            if (sig.hir_type.tag == .array) {
                try writer.print("    logic [{d}:0] ", .{sig.hir_type.elem_width - 1});
                try emitIdent(sig.name, writer);
                try writer.print(" [0:{d}];\n", .{sig.hir_type.array_len - 1});
            } else {
                const w = if (sig.hir_type.width > 0) sig.hir_type.width else 1;
                if (w <= 1) {
                    try writer.writeAll("    logic ");
                    try emitIdent(sig.name, writer);
                    try writer.writeAll(";\n");
                } else {
                    try writer.print("    logic [{d}:0] ", .{w - 1});
                    try emitIdent(sig.name, writer);
                    try writer.writeAll(";\n");
                }
            }
            try emitted_signals.put(sig.name, {});
        }

        if (mod.registers.len > 0 or mod.local_signals.len > 0) {
            try writer.writeAll("\n");
        }

        // Emit Submodule Instances
        for (mod.instances) |inst| {
            try writer.print("    {s} u_{s} (\n", .{ inst.module_name, inst.instance_name });
            for (inst.connections, 0..) |c, i| {
                const is_last = (i == inst.connections.len - 1);
                const comma = if (is_last) "" else ",";
                try writer.print("        .{s}(", .{c.port_name});
                try self.emitExpr(c.expr, writer);
                try writer.print("){s}\n", .{comma});
            }
            try writer.writeAll("    );\n\n");
        }

        // Emit Sequential always_ff for each register
        for (mod.registers) |reg| {
            if (reg.is_sync_stage) {
                try writer.writeAll("    (* ASYNC_REG = \"TRUE\" *)\n");
            }
            const has_rst = (reg.rst_name != null);
            if (has_rst) {
                if (reg.rst_active_low) {
                    try writer.print("    always_ff @(posedge {s} or negedge {s}) begin\n", .{ reg.clk_name, reg.rst_name.? });
                    try writer.print("        if (!{s}) begin\n", .{reg.rst_name.?});
                } else {
                    try writer.print("    always_ff @(posedge {s} or posedge {s}) begin\n", .{ reg.clk_name, reg.rst_name.? });
                    try writer.print("        if ({s}) begin\n", .{reg.rst_name.?});
                }

                if (reg.hir_type.tag == .array) {
                    try writer.print("            for (integer _i = 0; _i < {d}; _i = _i + 1) begin\n", .{reg.hir_type.array_len});
                    try writer.print("                {s}[_i] <= {d}'d0;\n", .{ reg.q_name, reg.hir_type.elem_width });
                    try writer.writeAll("            end\n");
                } else {
                    try writer.print("            {s} <= {d}'h{x};\n", .{ reg.q_name, reg.hir_type.width, reg.init_val });
                }
                try writer.writeAll("        end else begin\n");
                try writer.print("            {s} <= {s};\n", .{ reg.q_name, reg.d_name });
                try writer.writeAll("        end\n");
                try writer.writeAll("    end\n\n");
            } else {
                try writer.print("    always_ff @(posedge {s}) begin\n", .{reg.clk_name});
                try writer.print("        {s} <= {s};\n", .{ reg.q_name, reg.d_name });
                try writer.writeAll("    end\n\n");
            }
        }

        // Emit Combinational always_comb block
        if (mod.comb_stmts.len > 0) {
            try writer.writeAll("    always_comb begin\n");
            for (mod.comb_stmts) |stmt| {
                try self.emitStatement(&stmt, 2, writer);
            }
            try writer.writeAll("    end\n\n");
        }

        try writer.writeAll("endmodule\n");
    }

    fn emitStatement(self: *SystemVerilogEmitter, stmt: *const hir.HirStatement, indent: usize, writer: anytype) !void {
        switch (stmt.tag) {
            .assign => {
                try self.emitIndent(indent, writer);
                try self.emitExpr(stmt.data.assign.target, writer);
                try writer.writeAll(" = ");
                try self.emitExpr(stmt.data.assign.value, writer);
                try writer.writeAll(";\n");
            },
            .if_stmt => {
                const ifs = stmt.data.if_stmt;
                try self.emitIndent(indent, writer);
                try writer.writeAll("if (");
                try self.emitExpr(ifs.cond, writer);
                try writer.writeAll(") begin\n");

                for (ifs.then_body) |s| {
                    try self.emitStatement(&s, indent + 1, writer);
                }

                if (ifs.else_body) |eb| {
                    try self.emitIndent(indent, writer);
                    try writer.writeAll("end else begin\n");
                    for (eb) |s| {
                        try self.emitStatement(&s, indent + 1, writer);
                    }
                }
                try self.emitIndent(indent, writer);
                try writer.writeAll("end\n");
            },
            .case_stmt => {
                const cs = stmt.data.case_stmt;
                try self.emitIndent(indent, writer);
                try writer.writeAll("case (");
                try self.emitExpr(cs.expr, writer);
                try writer.writeAll(")\n");

                for (cs.branches) |b| {
                    try self.emitIndent(indent + 1, writer);
                    if (b.is_default) {
                        try writer.writeAll("default: begin\n");
                    } else {
                        const w = if (cs.expr.hir_type.width > 0) cs.expr.hir_type.width else 32;
                        for (b.pattern_values, 0..) |val, i| {
                            const comma = if (i == b.pattern_values.len - 1) "" else ", ";
                            try writer.print("{d}'d{d}{s}", .{ w, val, comma });
                        }
                        try writer.writeAll(": begin\n");
                    }

                    for (b.body) |s| {
                        try self.emitStatement(&s, indent + 2, writer);
                    }
                    try self.emitIndent(indent + 1, writer);
                    try writer.writeAll("end\n");
                }

                try self.emitIndent(indent, writer);
                try writer.writeAll("endcase\n");
            },
        }
    }

    fn emitExpr(self: *SystemVerilogEmitter, expr: *const hir.HirExpr, writer: anytype) !void {
        switch (expr.tag) {
            .lit => {
                const w = if (expr.hir_type.width > 0) expr.hir_type.width else 32;
                const raw = expr.data.lit.raw;
                const is_hex = (raw.len > 2 and (raw[1] == 'x' or raw[1] == 'X')) or
                    std.mem.indexOf(u8, raw, "'h") != null or
                    std.mem.indexOf(u8, raw, "'H") != null;
                const is_bin = (raw.len > 2 and (raw[1] == 'b' or raw[1] == 'B')) or
                    std.mem.indexOf(u8, raw, "'b") != null or
                    std.mem.indexOf(u8, raw, "'B") != null;

                if (is_hex) {
                    try writer.print("{d}'h{x}", .{ w, expr.data.lit.val });
                } else if (is_bin) {
                    try writer.print("{d}'b{b}", .{ w, expr.data.lit.val });
                } else {
                    try writer.print("{d}'d{d}", .{ w, expr.data.lit.val });
                }
            },
            .signal_ref => {
                try emitIdent(expr.data.signal_ref.name, writer);
            },
            .member => {
                try self.emitExpr(expr.data.member.target, writer);
                try writer.print(".{s}", .{expr.data.member.field});
            },
            .slice => {
                const s = expr.data.slice;
                if (s.is_downward) {
                    // Downward slice syntactic sugar: e.g. count[4..0] (high to low)
                    // Synthesizes bit reversal across the sliced window using Verilog streaming operator:
                    // {<<{target[high:low]}}
                    const hi = if (s.end > 0) s.end - 1 else 0;
                    const lo = s.start;
                    try writer.writeAll("{<<{");
                    try self.emitExpr(s.target, writer);
                    try writer.print("[{d}:{d}]", .{ hi, lo });
                    try writer.writeAll("}}");
                } else {
                    if (s.start == 0 and s.target.tag != .signal_ref and s.target.tag != .index and s.target.tag != .member) {
                        try writer.print("{d}'(", .{s.end - s.start});
                        try self.emitExpr(s.target, writer);
                        try writer.writeAll(")");
                    } else {
                        // Forward slice: [start..end) -> SV [end-1:start]
                        const hi = if (s.end > 0) s.end - 1 else 0;
                        const lo = s.start;
                        try self.emitExpr(s.target, writer);
                        if (hi == lo) {
                            try writer.print("[{d}]", .{lo});
                        } else {
                            try writer.print("[{d}:{d}]", .{ hi, lo });
                        }
                    }
                }
            },
            .index => {
                try self.emitExpr(expr.data.index.target, writer);
                try writer.writeAll("[");
                try self.emitExpr(expr.data.index.index, writer);
                try writer.writeAll("]");
            },
            .concat => {
                try writer.writeAll("{");
                for (expr.data.concat.args, 0..) |arg, i| {
                    const comma = if (i == expr.data.concat.args.len - 1) "" else ", ";
                    try self.emitExpr(arg, writer);
                    try writer.writeAll(comma);
                }
                try writer.writeAll("}");
            },
            .bit_reverse => {
                // SystemVerilog streaming operator reverses all bits in a word
                try writer.writeAll("{<<{");
                try self.emitExpr(expr.data.bit_reverse.target, writer);
                try writer.writeAll("}}");
            },
            .byte_swap => {
                // SystemVerilog byte streaming operator reverses 8-bit slices
                try writer.writeAll("{<<8{");
                try self.emitExpr(expr.data.byte_swap.target, writer);
                try writer.writeAll("}}");
            },
            .unary => {
                const u = expr.data.unary;
                const op_str = switch (u.op) {
                    .bang => "!",
                    .tilde => "~",
                    .minus => "-",
                    else => "",
                };
                try writer.print("{s}(", .{op_str});
                try self.emitExpr(u.operand, writer);
                try writer.writeAll(")");
            },
            .binary => {
                const b = expr.data.binary;
                const op_str = switch (b.op) {
                    .plus, .plus_percent => "+",
                    .minus, .minus_percent => "-",
                    .asterisk, .asterisk_percent => "*",
                    .slash => "/",
                    .percent => "%",
                    .ampersand => "&",
                    .pipe => "|",
                    .caret => "^",
                    .shl => "<<",
                    .shr => ">>",
                    .equal_equal => "==",
                    .bang_equal => "!=",
                    .less_than => "<",
                    .less_than_equal => "<=",
                    .greater_than => ">",
                    .greater_than_equal => ">=",
                    .ampersand_ampersand => "&&",
                    .pipe_pipe => "||",
                    else => "+",
                };
                try writer.writeAll("(");
                try self.emitExpr(b.left, writer);
                try writer.print(" {s} ", .{op_str});
                try self.emitExpr(b.right, writer);
                try writer.writeAll(")");
            },
            .mux => {
                const m = expr.data.mux;
                try writer.writeAll("(");
                try self.emitExpr(m.cond, writer);
                try writer.writeAll(" ? ");
                try self.emitExpr(m.then_expr, writer);
                try writer.writeAll(" : ");
                try self.emitExpr(m.else_expr, writer);
                try writer.writeAll(")");
            },
        }
    }

    fn emitIndent(self: *SystemVerilogEmitter, level: usize, writer: anytype) !void {
        _ = self;
        var i: usize = 0;
        while (i < level * 4) : (i += 1) {
            try writer.writeByte(' ');
        }
    }

    pub fn emitTestbench(self: *SystemVerilogEmitter, tb: *const hir.HirTestbench, writer: anytype) !void {
        var safe_name_buf: [256]u8 = undefined;
        var safe_len: usize = 0;
        const prefix = "tb_";
        @memcpy(safe_name_buf[0..prefix.len], prefix);
        safe_len += prefix.len;

        for (tb.name) |c| {
            if (safe_len >= safe_name_buf.len - 1) break;
            if (std.ascii.isAlphanumeric(c) or c == '_') {
                safe_name_buf[safe_len] = c;
                safe_len += 1;
            } else if (c == ' ' or c == '-' or c == '.') {
                safe_name_buf[safe_len] = '_';
                safe_len += 1;
            }
        }
        const tb_mod_name = safe_name_buf[0..safe_len];

        try writer.writeAll("/* verilator lint_off PROCASSINIT */\n");
        try writer.writeAll("/* verilator lint_off UNUSEDSIGNAL */\n");
        try writer.writeAll("/* verilator lint_off CASEINCOMPLETE */\n");
        try writer.print("module {s};\n\n", .{tb_mod_name});

        // 1. Emit signals
        for (tb.signals) |sig| {
            if (sig.hir_type.tag == .array) {
                try writer.print("    logic [{d}:0] ", .{sig.hir_type.elem_width - 1});
                try emitIdent(sig.name, writer);
                try writer.print(" [0:{d}];\n", .{sig.hir_type.array_len - 1});
            } else {
                const w = if (sig.hir_type.width > 0) sig.hir_type.width else 1;
                if (w <= 1) {
                    try writer.writeAll("    logic ");
                    try emitIdent(sig.name, writer);
                    if (sig.hir_type.tag == .reset and sig.hir_type.is_active_low) {
                        try writer.writeAll(" = 1;\n");
                    } else {
                        try writer.writeAll(" = 0;\n");
                    }
                } else {
                    try writer.print("    logic [{d}:0] ", .{w - 1});
                    try emitIdent(sig.name, writer);
                    try writer.writeAll(" = '0;\n");
                }
            }
        }
        try writer.writeAll("\n");

        // 2. Emit instances (DUT)
        for (tb.instances) |inst| {
            try writer.print("    {s} {s} (\n", .{ inst.module_name, inst.instance_name });
            for (inst.connections, 0..) |conn, i| {
                const is_last = (i == inst.connections.len - 1);
                const comma = if (is_last) "" else ",";
                try writer.print("        .{s}(", .{conn.port_name});
                try self.emitExpr(conn.expr, writer);
                try writer.print("){s}\n", .{comma});
            }
            try writer.writeAll("    );\n\n");
        }

        // 3. Emit clock generators
        for (tb.clock_gens) |cg| {
            if (cg.half_period_str.len > 0) {
                try writer.print("    always #{s} {s} = ~{s};\n", .{ cg.half_period_str, cg.clk_name, cg.clk_name });
            } else {
                const half = if (cg.period_ns >= 2) cg.period_ns / 2 else 1;
                try writer.print("    always #{d}ns {s} = ~{s};\n", .{ half, cg.clk_name, cg.clk_name });
            }
        }
        if (tb.clock_gens.len > 0) {
            try writer.writeAll("\n");
        }

        const default_clk: []const u8 = if (tb.clock_gens.len > 0) tb.clock_gens[0].clk_name else "clk";

        // 4. Emit initial stimulus block
        try writer.writeAll("    initial begin\n");

        for (tb.sim_stmts) |stmt| {
            switch (stmt.tag) {
                .trace => {
                    const t = stmt.data.trace;
                    try writer.print("        $dumpfile(\"{s}\");\n", .{t.vcd_path});
                    try writer.print("        $dumpvars(0, {s});\n", .{tb_mod_name});
                },
                .rst_pulse => {
                    const rp = stmt.data.rst_pulse;
                    const clk_to_use = default_clk;
                    if (rp.duration_raw) |dur| {
                        if (rp.active_low) {
                            try writer.print("        {s} = 1'b0;\n", .{rp.rst_name});
                            try writer.print("        #{s};\n", .{dur});
                            try writer.print("        {s} = 1'b1;\n", .{rp.rst_name});
                        } else {
                            try writer.print("        {s} = 1'b1;\n", .{rp.rst_name});
                            try writer.print("        #{s};\n", .{dur});
                            try writer.print("        {s} = 1'b0;\n", .{rp.rst_name});
                        }
                    } else {
                        const cycles = rp.cycles orelse 1;
                        if (rp.active_low) {
                            try writer.print("        {s} = 1'b0;\n", .{rp.rst_name});
                            try writer.print("        repeat ({d}) @(posedge {s});\n", .{ cycles, clk_to_use });
                            try writer.print("        {s} = 1'b1;\n", .{rp.rst_name});
                            try writer.print("        @(posedge {s});\n", .{clk_to_use});
                        } else {
                            try writer.print("        {s} = 1'b1;\n", .{rp.rst_name});
                            try writer.print("        repeat ({d}) @(posedge {s});\n", .{ cycles, clk_to_use });
                            try writer.print("        {s} = 1'b0;\n", .{rp.rst_name});
                            try writer.print("        @(posedge {s});\n", .{clk_to_use});
                        }
                    }
                },
                .step => {
                    const s = stmt.data.step;
                    const clk_to_use = s.clk_name orelse default_clk;
                    const edge_str = if (s.edge == .negedge) "negedge" else "posedge";
                    if (s.cycles == 1) {
                        try writer.print("        @({s} {s});\n", .{ edge_str, clk_to_use });
                    } else {
                        try writer.print("        repeat ({d}) @({s} {s});\n", .{ s.cycles, edge_str, clk_to_use });
                    }
                },
                .delay => {
                    const d = stmt.data.delay;
                    if (d.raw.len > 0) {
                        try writer.print("        #{s};\n", .{d.raw});
                    } else {
                        try writer.print("        #{d}ns;\n", .{d.ns});
                    }
                },
                .assign => {
                    const a = stmt.data.assign;
                    try writer.writeAll("        ");
                    try self.emitExpr(a.target, writer);
                    try writer.writeAll(" = ");
                    try self.emitExpr(a.value, writer);
                    try writer.writeAll(";\n");
                },
                .assert_stmt => {
                    const as = stmt.data.assert_stmt;
                    try writer.writeAll("        if (!(");
                    try self.emitExpr(as.cond, writer);
                    try writer.writeAll(")) begin\n");
                    if (as.msg) |msg| {
                        try writer.print("            $error(\"[FAIL] {s}\");\n", .{msg});
                    } else {
                        try writer.print("            $error(\"[FAIL] Assertion failed in test '{s}'\");\n", .{tb.name});
                    }
                    try writer.writeAll("            $fatal(1);\n");
                    try writer.writeAll("        end\n");
                },
                .print => {
                    const p = stmt.data.print;
                    try writer.print("        $display(\"{s}\");\n", .{p.fmt});
                },
                .wait_for => {
                    const wf = stmt.data.wait_for;
                    if (wf.timeout_raw) |t_raw| {
                        try writer.writeAll("        fork\n");
                        try writer.writeAll("            begin\n");
                        try writer.writeAll("                wait (");
                        try self.emitExpr(wf.cond, writer);
                        try writer.writeAll(");\n");
                        try writer.writeAll("            end\n");
